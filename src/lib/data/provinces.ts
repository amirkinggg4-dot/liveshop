/** شهرهای یک استان — نام ورودی با normalizeFa یکدست می‌شود تا
    «چهارمحال وبختیاری» یا حروف عربی هم پیدا شود؛ نام ناشناخته → [] */
export function citiesOf(provinceName: string): string[] {
  const key = normalizeFa(provinceName);
  const found = PROVINCES.find((p) => normalizeFa(p.name) === key);
  return found ? [...found.cities] : [];
}
