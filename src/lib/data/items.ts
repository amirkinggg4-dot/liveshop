export const ALL_ITEMS: ShopItem[] = [...ITEMS_SH1, ...ITEMS_SH2, ...ITEMS_SH3];

export function getShowItems(showId: string): ShopItem[] {
  const map: Record<string, ShopItem[]> = {
    sh1: ITEMS_SH1,
    sh2: ITEMS_SH2,
    sh3: ITEMS_SH3,
    sh4: ITEMS_SH1.slice(0, 4),
    sh5: ITEMS_SH2.slice(0, 4),
  };
  return map[showId] ?? ITEMS_SH1;
}

export function getItem(id: string): ShopItem | undefined {
  return ALL_ITEMS.find((i) => i.id === id);
}

/** آیتم فعلیِ در مزایدهٔ یک شو (برای پیش‌نمایش کارت‌ها و لایو) */
export function getAuctionItem(showId: string): ShopItem | undefined {
  return getShowItems(showId).find((i) => i.status === "auction");
}
